"""Local SQLite / production Supabase API ledger interface.

Production sends native PostgreSQL statements through a private, service-role
RPC. No PostgreSQL password, direct TCP connection or SQLite file is required.
A connection journals statements; previews roll back and commit replays the
whole transaction under a database-scoped advisory lock.
"""
from __future__ import annotations

import os
import re
import sqlite3 as local_sqlite
from pathlib import Path
from urllib.parse import unquote, urlsplit

Error = local_sqlite.Error
OperationalError = local_sqlite.OperationalError
IntegrityError = local_sqlite.IntegrityError
Row = local_sqlite.Row
Connection = local_sqlite.Connection

DATABASES = {'snapshots.db', 'module2_decisions.db', 'module2_intraday.db', 'module2_historical_news.db'}


def cloud_enabled():
    mode = os.getenv('OPENBELL_STORAGE_BACKEND', 'supabase' if os.getenv('VERCEL') else 'sqlite')
    if mode not in ('supabase', 'sqlite'):
        raise OperationalError('OPENBELL_STORAGE_BACKEND must be supabase or sqlite')
    if os.getenv('VERCEL') and mode != 'supabase':
        raise OperationalError('SQLite is disabled on Vercel; configure Supabase production storage')
    return mode == 'supabase'


def database_name(path):
    value = str(path)
    if value.startswith('file:'):
        value = unquote(urlsplit(value).path)
    name = value.replace('\\', '/').rsplit('/', 1)[-1]
    if name not in DATABASES:
        raise OperationalError('Unsupported production ledger identity')
    return name


def exists(path):
    return True if cloud_enabled() and database_name(path) else Path(path).exists()


def _literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return '1' if value else '0'
    if isinstance(value, (bytes, bytearray, memoryview)):
        return "decode('" + bytes(value).hex() + "','hex')"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        import math
        if not math.isfinite(value):
            raise OperationalError('Nonfinite ledger value')
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def translate(statement, parameters=(), database='snapshots.db'):
    """Translate the existing parameterized ledger dialect, never user SQL."""
    import sqlglot
    from sqlglot import exp
    schema = 'openbell_' + database.removesuffix('.db')
    statement = statement.strip().rstrip(';')
    if re.fullmatch(r'BEGIN(?: IMMEDIATE)?', statement, re.I):
        return None
    trigger = re.fullmatch(r"CREATE TRIGGER IF NOT EXISTS (\w+) BEFORE (UPDATE|DELETE) ON (\w+) BEGIN SELECT RAISE\(ABORT,\s*'[^']*'\);?\s*END", statement, re.I | re.S)
    if trigger:
        # The installed view's INSTEAD OF writer enforces the same immutable
        # policy; PostgreSQL views cannot have these SQLite BEFORE triggers.
        return None
    if re.match(r'^CREATE\s+(UNIQUE\s+)?INDEX\b', statement, re.I):
        return None  # existing Supabase row-store indexes own physical storage
    if re.match(r'^PRAGMA\s+(journal_mode|busy_timeout)\b', statement, re.I):
        return None
    info = re.fullmatch(r'PRAGMA\s+table_info\(["\']?([A-Za-z_]\w*)["\']?\)', statement, re.I)
    if info:
        table = info[1]
        return f"""SELECT a.attnum-1 AS cid,a.attname AS name,
            format_type(a.atttypid,a.atttypmod) AS type,
            CASE WHEN a.attnotnull THEN 1 ELSE 0 END AS \"notnull\",
            pg_get_expr(d.adbin,d.adrelid) AS dflt_value,
            COALESCE(array_position(i.indkey::smallint[],a.attnum),0)::int AS pk
            FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
            JOIN pg_namespace n ON n.oid=c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
            LEFT JOIN pg_index i ON i.indrelid=c.oid AND i.indisprimary
            WHERE n.nspname={_literal(schema)} AND c.relname={_literal(table)}
            AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum"""
    if re.match(r'^PRAGMA\b', statement, re.I):
        raise OperationalError('Unsupported production schema pragma')
    ignore = bool(re.match(r'^INSERT\s+OR\s+IGNORE\b', statement, re.I))
    statement = re.sub(r'^INSERT\s+OR\s+IGNORE\b', 'INSERT', statement, flags=re.I)
    statement = re.sub(r'^CREATE\s+VIEW\s+IF\s+NOT\s+EXISTS', 'CREATE OR REPLACE VIEW', statement, flags=re.I)
    # SQLite rowid-backed integer primary keys also auto-generate without the
    # AUTOINCREMENT keyword. Use BIGINT to retain original imported identifiers.
    statement = re.sub(r'\bid\s+INTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?',
                       'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement, flags=re.I)
    # The only GLOB in the ledger is the validated date/slot pattern.
    statement = statement.replace("slot_key GLOB '????-??-??_[0-9][0-9][0-9][0-9]'",
                                  "REGEXP_LIKE(slot_key, '^[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{4}$')")
    # Bind by textual position. sqlglot's tree walks visit placeholders out of
    # source order (e.g. LIMIT ? before WHERE LOWER(?)), so number each '?'
    # token as it appears in the SQL text before parsing.
    from sqlglot.tokens import TokenType
    marks = [token.start for token in sqlglot.Dialect.get_or_raise('sqlite').tokenize(statement)
             if token.token_type == TokenType.PLACEHOLDER and token.text == '?']
    for index, start in reversed(list(enumerate(marks))):
        statement = statement[:start] + f':obp{index}' + statement[start + 1:]
    tree = sqlglot.parse_one(statement, read='sqlite')
    if not isinstance(tree, (exp.Select, exp.Union, exp.Insert, exp.Update, exp.Create, exp.Alter)):
        raise OperationalError('Destructive or unsupported production ledger statement')
    if any(isinstance(node,(exp.Delete,exp.Drop,exp.Command)) for node in tree.walk()):
        raise OperationalError('Destructive ledger subquery is not permitted')
    # Schema catalog checks retain the old reader contract, without SQLite.
    for table in list(tree.find_all(exp.Table)):
        if table.name == 'sqlite_master':
            alias = table.alias_or_name
            catalog = sqlglot.parse_one(f"SELECT table_name AS name,CASE WHEN table_name='subscription_training_capture_v1' THEN 'view' ELSE 'table' END AS type FROM information_schema.tables WHERE table_schema={_literal(schema)}", read='postgres')
            table.replace(exp.Subquery(this=catalog, alias=exp.TableAlias(this=exp.to_identifier(alias))))
    values = list(parameters)
    used = set()
    for placeholder in list(tree.find_all(exp.Placeholder)):
        match = re.fullmatch(r'obp(\d+)', placeholder.name or '')
        if not match:
            raise OperationalError('Unsupported ledger placeholder')
        index = int(match[1])
        if index >= len(values):
            raise OperationalError('Missing ledger bind value')
        used.add(index)
        placeholder.replace(sqlglot.parse_one(_literal(values[index]), read='postgres'))
    if len(used) != len(values):
        raise OperationalError('Unused ledger bind value')
    result = tree.sql(dialect='postgres')
    if ignore:
        result += ' ON CONFLICT DO NOTHING'
    return result


class CloudRow:
    def __init__(self, columns, values):
        self._columns, self._values = columns, values

    def keys(self):
        return self._columns

    def __getitem__(self, key):
        return self._values[self._columns.index(key)] if isinstance(key, str) else self._values[key]

    def __iter__(self):
        return iter(self._values)


class Cursor:
    def __init__(self, result, factory=None):
        self.rowcount = int(result.get('rowcount', 0))
        self.lastrowid = None
        columns = result.get('columns') or []
        binary = set(result.get('binary_columns') or [])
        self.description = [(name, None, None, None, None, None, None) for name in columns]
        self._rows = []
        for row in result.get('rows') or []:
            values = [bytes.fromhex(row[k][2:]) if k in binary and row.get(k) is not None else row.get(k) for k in columns]
            self._rows.append(CloudRow(columns, values) if factory is Row else tuple(values))

    def fetchone(self):
        return self._rows.pop(0) if self._rows else None

    def fetchall(self):
        rows, self._rows = self._rows, []
        return rows

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        pass


class CloudConnection:
    def __init__(self, path, *, client=None, readonly=False):
        self.database = database_name(path)
        self.client = client
        self.readonly = readonly
        self.row_factory = None
        self.total_changes = 0
        self._journal = []
        self._has_writes = False
        self._closed = False

    def _run(self, statements, preview):
        if self._closed:
            raise OperationalError('Ledger connection is closed')
        if self.client is None:
            from db.supabase_client import get_supabase
            self.client = get_supabase(use_service_role=True)
        try:
            result = self.client.rpc('openbell_ledger_transaction_v1', {
                'p_database': self.database, 'p_statements': statements, 'p_preview': preview,
            }).execute().data
            return result['results']
        except Exception as exc:
            # Do not put SQL, payloads or credential-bearing requests in errors.
            code = getattr(exc, 'code', '')
            error = IntegrityError if str(code).startswith('23') else OperationalError
            raise error('Supabase ledger transaction failed' + (f' ({code})' if code else '')) from None

    def execute(self, statement, parameters=()):
        sql = translate(statement, parameters, self.database)
        if sql is None:
            return Cursor({})
        read = bool(re.match(r'^(SELECT|WITH)\b', sql, re.I))
        if not read and self.readonly:
            raise OperationalError('Read-only production ledger connection')
        if not read:
            self._journal.append(sql)
            self._has_writes = True
            # DDL has no rowcount and does not need a preview until queried.
            if re.match(r'^(CREATE|ALTER)\b', sql, re.I):
                return Cursor({})
        statements = self._journal + ([sql] if read else [])
        results = self._run(statements, preview=True)
        result = results[-1]
        if read and not any(re.match(r'^(INSERT|UPDATE)\b', s if isinstance(s,str) else s['sql'], re.I) for s in self._journal):
            self._journal.append({'sql':sql,'expected_rows':result.get('rows',[])})
        self.total_changes = sum(int(r.get('rowcount', 0)) for r in results if r.get('mutation'))
        return Cursor(result, self.row_factory)

    def cursor(self):
        return BoundCursor(self)

    def executescript(self, script):
        # complete_statement is a tokenizer only: it never opens a local DB and
        # correctly retains semicolons inside immutable-history trigger bodies.
        current = ''
        for character in script:
            current += character
            if character == ';' and local_sqlite.complete_statement(current):
                self.execute(current)
                current = ''
        if current.strip():
            self.execute(current)
        return Cursor({})

    def executemany(self, sql, rows):
        for values in rows:
            self.execute(sql, values)
        return Cursor({})

    def commit(self):
        if self._has_writes:
            results = self._run(self._journal, preview=False)
            self.total_changes = sum(int(r.get('rowcount', 0)) for r in results if r.get('mutation'))
        self._journal.clear()
        self._has_writes = False

    def rollback(self):
        self._journal.clear()
        self._has_writes = False

    def close(self):
        self.rollback()
        self._closed = True

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        self.rollback() if kind else self.commit()


class BoundCursor:
    def __init__(self,connection):
        self.connection=connection;self.result=Cursor({})

    def execute(self,sql,parameters=()):
        self.result=self.connection.execute(sql,parameters)
        return self

    def __getattr__(self,name):
        return getattr(self.result,name)

    def __iter__(self):
        return iter(self.result)


def connect(database, timeout=5, uri=False, **kwargs):
    if not cloud_enabled():
        return local_sqlite.connect(database, timeout=timeout, uri=uri, **kwargs)
    return CloudConnection(database, readonly=uri and 'mode=ro' in str(database))


def remote_collector_active(client=None):
    """The legacy local mirror must not overwrite the cloud writer's IDs."""
    try:
        c=CloudConnection('snapshots.db',client=client)
        if not c.execute("SELECT to_regclass('openbell_snapshots._openbell_collector_lease')").fetchone()[0]:return False
        row=c.execute("SELECT expires_at>clock_timestamp() FROM _openbell_collector_lease WHERE name='collector'").fetchone()
        return bool(row and row[0])
    finally:
        if 'c' in locals():c.close()
