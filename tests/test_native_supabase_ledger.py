import json
import copy
from pathlib import Path
from types import SimpleNamespace
import pytest
from db import ledger


class Client:
    def __init__(self):self.calls=[]
    def rpc(self,name,args):
        self.calls.append((name,copy.deepcopy(args)))
        return SimpleNamespace(execute=lambda:SimpleNamespace(data={'results':[
            {'columns':['id','raw'],'binary_columns':['raw'],'rows':[{'id':7,'raw':'\\x616263'}],
             'rowcount':1,'mutation':isinstance(s,str) and s.startswith('INSERT')}
            for s in args['p_statements']]}))


def test_vercel_cannot_fall_back_to_sqlite(monkeypatch):
    monkeypatch.setenv('VERCEL','1');monkeypatch.setenv('OPENBELL_STORAGE_BACKEND','sqlite')
    with pytest.raises(ledger.OperationalError):ledger.connect('snapshots.db')


def test_cloud_connection_uses_api_and_preserves_binary_rows(monkeypatch):
    monkeypatch.setenv('OPENBELL_STORAGE_BACKEND','supabase')
    monkeypatch.setattr(ledger.local_sqlite,'connect',lambda *a,**k:pytest.fail('SQLite opened in production'))
    client=Client();c=ledger.CloudConnection('snapshots.db',client=client);c.row_factory=ledger.Row
    row=c.execute('SELECT id,raw FROM x WHERE id=?',(7,)).fetchone()
    assert dict(row)=={'id':7,'raw':b'abc'} and row[0]==7
    assert client.calls[0][1]['p_preview'] is True


def test_changes_commit_as_one_journal_and_rollback_never_writes():
    client=Client();c=ledger.CloudConnection('snapshots.db',client=client)
    c.execute('INSERT INTO x(id) VALUES (?)',(7,));c.execute('INSERT INTO x(id) VALUES (?)',(8,));c.rollback()
    assert all(args['p_preview'] for _,args in client.calls)
    c.execute('INSERT INTO x(id) VALUES (?)',(9,));c.commit()
    commits=[args for _,args in client.calls if not args['p_preview']]
    assert len(commits)==1 and len(commits[0]['p_statements'])==1


def test_read_before_write_becomes_optimistic_commit_precondition():
    client=Client();c=ledger.CloudConnection('snapshots.db',client=client)
    c.execute('SELECT id,raw FROM x WHERE id=?',(7,));c.execute('UPDATE x SET id=? WHERE id=?',(8,7));c.commit()
    args=client.calls[-1][1]
    assert args['p_statements'][0]['expected_rows']==[{'id':7,'raw':'\\x616263'}]
    assert len(args['p_statements'])==2


def test_cloud_readonly_and_destructive_queries_are_blocked():
    c=ledger.CloudConnection('snapshots.db',client=Client(),readonly=True)
    with pytest.raises(ledger.OperationalError):c.execute('UPDATE x SET id=1')
    for sql in ('DELETE FROM x','DROP TABLE x','TRUNCATE x'):
        with pytest.raises(ledger.OperationalError):ledger.translate(sql)


def test_parameter_quoting_does_not_turn_user_text_into_sql():
    sql=ledger.translate('INSERT INTO x(name,raw) VALUES (?,?)',("O'Brien'); DROP TABLE x; --",b'\x00\xff'))
    assert "O''Brien''); DROP TABLE x; --" in sql
    assert "DECODE('00ff', 'hex')" in sql


def test_bind_values_follow_textual_placeholder_order():
    sql=ledger.translate('SELECT a FROM t WHERE LOWER(c) = LOWER(?) OR ipo_id = ? ORDER BY r DESC LIMIT ?',
                         ('Crystal Crop Protection','610',24))
    assert "LOWER('Crystal Crop Protection')" in sql and "ipo_id = '610'" in sql and sql.endswith('LIMIT 24')
    question=ledger.translate("SELECT a FROM t WHERE note = 'why?' AND id = ?",(5,))
    assert "note = 'why?'" in question and 'id = 5' in question
    with pytest.raises(ledger.OperationalError):ledger.translate('SELECT a FROM t WHERE id = ?',())
    with pytest.raises(ledger.OperationalError):ledger.translate('SELECT a FROM t WHERE id = ?',(1,2))


def test_existing_trigger_and_slot_contracts_are_preserved():
    sql=ledger.translate("SELECT slot_key FROM x WHERE slot_key GLOB '????-??-??_[0-9][0-9][0-9][0-9]'")
    assert "slot_key ~ '^[0-9]{4}" in sql
    assert ledger.translate("PRAGMA busy_timeout=5000") is None
    assert ledger.translate("BEGIN IMMEDIATE") is None
    ddl=ledger.translate('CREATE TABLE x(id INTEGER PRIMARY KEY,raw BLOB)')
    assert 'GENERATED BY DEFAULT AS IDENTITY' in ddl and 'BYTEA' in ddl


